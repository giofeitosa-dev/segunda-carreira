-- Flyway V1 baseline: schema inicial (17 tabelas)
-- Compatível com H2 em modo PostgreSQL e PostgreSQL 16

-- -----------------------------------------------------
-- Tabela perfil (core entity)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS perfil (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(200) NOT NULL,
    email VARCHAR(200) NOT NULL,
    area_atual VARCHAR(200) NOT NULL,
    area_alvo VARCHAR(200) NOT NULL,
    pretensao_salarial DECIMAL(19,2),
    disponibilidade VARCHAR(50),
    telefone VARCHAR(30),
    cidade VARCHAR(200),
    resumo VARCHAR(1500),
    linkedin VARCHAR(500),
    github VARCHAR(500),
    data_criacao TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP,
    CONSTRAINT pk_perfil PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela experiencia
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS experiencia (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    cargo VARCHAR(200) NOT NULL,
    empresa VARCHAR(200) NOT NULL,
    ano_inicio INTEGER NOT NULL,
    ano_fim INTEGER,
    descricao TEXT,
    CONSTRAINT fk_experiencia_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT pk_experiencia PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela formacao
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS formacao (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    curso VARCHAR(200) NOT NULL,
    instituicao VARCHAR(200) NOT NULL,
    ano_conclusao INTEGER,
    CONSTRAINT fk_formacao_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT pk_formacao PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela projeto
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS projeto (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT,
    ano_inicio INTEGER,
    ano_fim INTEGER,
    CONSTRAINT fk_projeto_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT pk_projeto PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela idioma
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS idioma (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    idioma VARCHAR(100) NOT NULL,
    nivel VARCHAR(20) NOT NULL,
    CONSTRAINT fk_idioma_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT pk_idioma PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela certificacao
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS certificacao (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    nome VARCHAR(200) NOT NULL,
    instituicao VARCHAR(200),
    ano_obtencao INTEGER,
    CONSTRAINT fk_certificacao_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT pk_certificacao PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela competencia
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS competencia (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT,
    CONSTRAINT pk_competencia PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela perfil_competencia (join table many-to-many)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS perfil_competencia (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    competencia_id BIGINT NOT NULL,
    nivel VARCHAR(20),
    anos_experiencia INTEGER,
    CONSTRAINT fk_pc_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT fk_pc_competencia FOREIGN KEY (competencia_id) REFERENCES competencia (id) ON DELETE CASCADE,
    CONSTRAINT uk_perfil_competencia UNIQUE (perfil_id, competencia_id),
    CONSTRAINT pk_perfil_competencia PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela vaga
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS vaga (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    empresa VARCHAR(200),
    salario DECIMAL(19,2),
    area VARCHAR(200),
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    data_publicacao TIMESTAMP NOT NULL,
    CONSTRAINT pk_vaga PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela inscricao
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS inscricao (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    vaga_id BIGINT NOT NULL,
    tipo_invocao VARCHAR(50) NOT NULL,
    referencia_id VARCHAR(200),
    data_inscricao TIMESTAMP NOT NULL,
    lembrete_agendado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_inscricao_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT fk_inscricao_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE CASCADE,
    CONSTRAINT pk_inscricao PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela trilha
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS trilha (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT,
    CONSTRAINT pk_trilha PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela modulo_trilha
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS modulo_trilha (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    trilha_id BIGINT NOT NULL,
    ordem INTEGER NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    CONSTRAINT fk_modulo_trilha FOREIGN KEY (trilha_id) REFERENCES trilha (id) ON DELETE CASCADE,
    CONSTRAINT pk_modulo_trilha PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela mentoria
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS mentoria (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT,
    modulo_trilha_id BIGINT,
    status VARCHAR(50) NOT NULL,
    CONSTRAINT fk_mentoria_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE SET NULL,
    CONSTRAINT fk_mentoria_modulo FOREIGN KEY (modulo_trilha_id) REFERENCES modulo_trilha (id) ON DELETE SET NULL,
    CONSTRAINT pk_mentoria PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela metrica_funil (escudo)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS metrica_funil (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT,
    vaga_id BIGINT,
    etapa VARCHAR(50) NOT NULL,
    razao DECIMAL(5,2),
    alerta VARCHAR(10),
    CONSTRAINT fk_mf_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE SET NULL,
    CONSTRAINT fk_mf_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE SET NULL,
    CONSTRAINT pk_metrica_funil PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela regra_idade (escudo)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS regra_idade (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    regra VARCHAR(100) NOT NULL,
    descricao TEXT,
    idade_min INTEGER,
    idade_max INTEGER,
    CONSTRAINT pk_regra_idade PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela sinal_idade (escudo)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS sinal_idade (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    regra_idade_id BIGINT NOT NULL,
    perfil_id BIGINT,
    vaga_id BIGINT,
    resultado VARCHAR(50),
    CONSTRAINT fk_sinal_regra FOREIGN KEY (regra_idade_id) REFERENCES regra_idade (id) ON DELETE CASCADE,
    CONSTRAINT fk_sinal_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE SET NULL,
    CONSTRAINT fk_sinal_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE SET NULL,
    CONSTRAINT pk_sinal_idade PRIMARY KEY (id)
);

-- -----------------------------------------------------
-- Tabela solicitacao_revisao (escudo)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS solicitacao_revisao (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    perfil_id BIGINT NOT NULL,
    vaga_id BIGINT,
    motivo VARCHAR(500) NOT NULL,
    status VARCHAR(50) NOT NULL,
    data_solicitacao TIMESTAMP NOT NULL,
    CONSTRAINT fk_sr_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE,
    CONSTRAINT fk_sr_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE SET NULL,
    CONSTRAINT pk_solicitacao_revisao PRIMARY KEY (id)
);

