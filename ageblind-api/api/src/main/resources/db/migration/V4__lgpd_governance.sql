-- Flyway V4: configuração de retenção LGPD (ciclo 003)
-- Tabela opcional para armazenar políticas de retenção por tipo de dado

CREATE TABLE IF NOT EXISTS configuracao_retencao (
    id            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tipo_dado     VARCHAR(100) NOT NULL,
    dias_retencao INTEGER NOT NULL,
    ativo         BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_configuracao_retencao PRIMARY KEY (id),
    CONSTRAINT uk_configuracao_retencao_tipo UNIQUE (tipo_dado)
);

-- Registro padrão: perfil retido por 365 dias de inatividade
INSERT INTO configuracao_retencao (tipo_dado, dias_retencao, ativo)
VALUES ('perfil', 365, TRUE)
ON CONFLICT (tipo_dado) DO NOTHING;

-- Auditoria é imutável: sem retenção (não entra na purga)
INSERT INTO configuracao_retencao (tipo_dado, dias_retencao, ativo)
VALUES ('auditoria_seguranca', 0, FALSE)
ON CONFLICT (tipo_dado) DO NOTHING;

-- Índice para consulta rápida por tipo
CREATE INDEX IF NOT EXISTS idx_configuracao_retencao_tipo ON configuracao_retencao (tipo_dado);

