-- Flyway V2: entidade Usuario (identidade autenticável JWT)
-- Ciclo 001-jwt-security-baseline — posse via usuario.perfil_id (1:1 opcional)

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(250) NOT NULL,
    senha VARCHAR(100) NOT NULL,
    papel VARCHAR(20) NOT NULL,
    perfil_id BIGINT,
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('CANDIDATO', 'RH', 'EMPRESA')),
    CONSTRAINT fk_usuario_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_usuario_perfil ON usuario (perfil_id);
