-- Flyway V3: tabela de auditoria de segurança
-- Ciclo 002-observability-audit — registro imutável de eventos de segurança

CREATE TABLE IF NOT EXISTS auditoria_seguranca (
    id            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    usuario_id    BIGINT,
    acao          VARCHAR(100) NOT NULL,
    recurso       VARCHAR(500) NOT NULL,
    ip            VARCHAR(45) NOT NULL,
    data_hora     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    correlation_id VARCHAR(64) NOT NULL,
    CONSTRAINT pk_auditoria_seguranca PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoria_usuario ON auditoria_seguranca (usuario_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_data_hora ON auditoria_seguranca (data_hora);
CREATE INDEX IF NOT EXISTS idx_auditoria_correlation ON auditoria_seguranca (correlation_id);
